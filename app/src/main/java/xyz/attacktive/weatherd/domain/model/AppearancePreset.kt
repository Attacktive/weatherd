package xyz.attacktive.weatherd.domain.model

data class SavedAppearancePreset(
	val id: String,
	val name: String,
	val snapshot: AppearancePresetSnapshot
)

data class AppearancePresetSnapshot(
	val backdropScene: BackdropScene,
	val showWeatherLabel: Boolean,
	val showLocationLabel: Boolean,
	val precipitationIntensityScale: Float,
	val windIntensityScale: Float,
	val cloudIntensityScale: Float,
	val cloudSizeScale: Float,
	val cloudCountScale: Float,
	val cloudContrastScale: Float,
	val skyBrightnessScale: Float,
	val nightBrightnessScale: Float,
	val skySaturationScale: Float,
	val skyColorPreset: SkyColorPreset,
	val sunVisible: Boolean,
	val moonVisible: Boolean,
	val sunSizeScale: Float,
	val sunHorizontalPosition: Float = DEFAULT_SUN_HORIZONTAL_POSITION,
	val moonSizeScale: Float = 1f,
	val moonOpacity: Float = 1f,
	val sunColorPreset: SunColorPreset,
	val sunStyle: SunStyle = SunStyle.CLASSIC,
	val sunbeamMode: SunbeamMode = SunbeamMode.THROUGH_CLOUDS,
	val lensFlareEnabled: Boolean,
	val rainbowSizeScale: Float = 1f,
	val lensFlareMotionEnabled: Boolean,
	val distantAircraftEnabled: Boolean = true,
	val birdFlockSize: BirdFlockSize = BirdFlockSize.SMALL,
	val birdAppearanceInterval: BirdAppearanceInterval = BirdAppearanceInterval.NATURAL,
	val glassDropletsEnabled: Boolean = false,
	val treesEnabled: Boolean = false,
	val treeStyle: TreeStyle = TreeStyle.EVERGREEN,
	val labelVerticalPosition: Float = DEFAULT_LABEL_VERTICAL_POSITION,
	val wallpaperDimmingStrength: Float = 0f,
	val statusBarShadeStrength: Float = 0f
)

fun AppSettings.toAppearancePresetSnapshot() = AppearancePresetSnapshot(
	backdropScene = backdropScene,
	showWeatherLabel = showWeatherLabel,
	showLocationLabel = showLocationLabel,
	precipitationIntensityScale = precipitationIntensityScale,
	windIntensityScale = windIntensityScale,
	cloudIntensityScale = cloudIntensityScale,
	cloudSizeScale = cloudSizeScale,
	cloudCountScale = cloudCountScale,
	cloudContrastScale = cloudContrastScale,
	skyBrightnessScale = skyBrightnessScale,
	nightBrightnessScale = nightBrightnessScale,
	skySaturationScale = skySaturationScale,
	skyColorPreset = skyColorPreset,
	sunVisible = sunVisible,
	moonVisible = moonVisible,
	sunSizeScale = sunSizeScale,
	sunHorizontalPosition = normalizeSunHorizontalPosition(sunHorizontalPosition),
	moonSizeScale = normalizeMoonSizeScale(moonSizeScale),
	moonOpacity = normalizeMoonOpacity(moonOpacity),
	sunColorPreset = sunColorPreset,
	sunStyle = sunStyle,
	sunbeamMode = sunbeamMode,
	lensFlareEnabled = lensFlareEnabled,
	rainbowSizeScale = normalizeRainbowSizeScale(rainbowSizeScale),
	lensFlareMotionEnabled = lensFlareMotionEnabled,
	distantAircraftEnabled = distantAircraftEnabled,
	birdFlockSize = birdFlockSize,
	birdAppearanceInterval = birdAppearanceInterval,
	glassDropletsEnabled = glassDropletsEnabled,
	treesEnabled = treesEnabled,
	treeStyle = treeStyle,
	labelVerticalPosition = labelVerticalPosition,
	wallpaperDimmingStrength = normalizeReadabilityStrength(wallpaperDimmingStrength),
	statusBarShadeStrength = normalizeReadabilityStrength(statusBarShadeStrength)
)

